"""Input-protection simulation runner.
Generates LTspice netlists (netlists/*.cir), runs LTspice in batch mode, reads the raw
waveforms, computes metrics and plots. EVERY number in results/ comes from an LTspice run.
Usage:  python run_sims.py            (LTspice path: auto-detected, or set LTSPICE_EXE)
"""
import os, sys, math, shutil, subprocess, csv
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from rawread import read_raw

HERE = os.path.dirname(os.path.abspath(__file__))
NET, RES, PLT = (os.path.join(HERE, d) for d in ("netlists", "results", "plots"))
RAW = os.path.join(RES, "raw")
for d in (NET, RES, PLT, RAW):
    os.makedirs(d, exist_ok=True)


def find_ltspice():
    cands = [os.environ.get("LTSPICE_EXE", ""),
             os.path.expandvars(r"%LOCALAPPDATA%\Programs\ADI\LTspice\LTspice.exe"),
             r"C:\Program Files\ADI\LTspice\LTspice.exe",
             r"C:\Program Files\LTC\LTspiceXVII\XVIIx64.exe"]
    for c in cands:
        if c and os.path.exists(c):
            return c
    sys.exit("LTspice not found. Install it or set LTSPICE_EXE.")


# ---- assumptions (component ratings are typical datasheet values: VERIFY against real datasheets) ----
UA = 13.5   # ISO supply voltage during pulse tests
RATINGS = dict(tvs_ppk=600.0, tvs_ipp=11.3, tvs_vc=53.3, tvs_e=0.6,   # SMBJ33CA, 10/1000 us; E ref = 600 W x 1 ms
               fet_vds=60.0, fet_vgs=20.0, ic_vin=42.0, cin_v=50.0)
TVS_MODEL = ".model TVS D(Is=1n Rs=1.47 Bv=36.7 Ibv=1m N=1) ; SMBJ33CA approx: Vbr 36.7 V @1 mA, Rd=(53.3-36.7)/11.3 ohm"
FET_MODEL = ".model PFET VDMOS(pchan Vto=-2.5 Kp=7 Rd=3m Rs=2m Rg=3 Cgs=1n Cgdmax=300p Cgdmin=100p Cjo=300p Is=1e-9 Rb=5m)"
T0 = 1e-6


def dexp(us, td, tr):
    """Double-exponential pulse added to UA; peak normalised to us. td ~ half-value time, tr ~ 10-90 % rise."""
    tau_d, tau_r = td / math.log(2), tr / 2.2
    xs = math.log(tau_d / tau_r) * tau_d * tau_r / (tau_d - tau_r)
    k = us / (math.exp(-xs / tau_d) - math.exp(-xs / tau_r))
    return (f"{UA}+{k:.6g}*u(time-{T0})*(exp(-(time-{T0})/{tau_d:.6g})-exp(-(time-{T0})/{tau_r:.6g}))")


def loaddump(us, td, tr=10e-3, t0=50e-3):
    return (f"{UA}+({us}-{UA})*(u(time-{t0})*(time-{t0})/{tr}*(1-u(time-{t0 + tr}))"
            f"+u(time-{t0 + tr})*exp(-(time-{t0 + tr})*0.693147/{td}))")


REVS = [("A", "10k"), ("B", "1k")]   # design revisions: gate pull-down resistor

# name, description, source (B-source expression or PWL), Ri (ohm), tstop (s), max step (s)
SC = [
    ("P1", "ISO 7637-2 pulse 1: Us=-100 V, Ri=10 ohm, td=2 ms, tr=1 us", dexp(-100, 2e-3, 1e-6), 10, 20e-3, 0.2e-6),
    ("P2a", "ISO 7637-2 pulse 2a: Us=+50 V, Ri=2 ohm, td=50 us, tr=1 us", dexp(50, 50e-6, 1e-6), 2, 400e-6, 20e-9),
    ("P3a", "ISO 7637-2 pulse 3a: Us=-150 V, Ri=50 ohm, td=150 ns, tr=5 ns (single pulse)", dexp(-150, 150e-9, 5e-9), 50, 1.5e-6, 0.2e-9),
    ("P3b", "ISO 7637-2 pulse 3b: Us=+150 V, Ri=50 ohm, td=150 ns, tr=5 ns (single pulse)", dexp(150, 150e-9, 5e-9), 50, 1.5e-6, 0.2e-9),
    ("P4", "ISO 7637-2 pulse 4 (cranking dip, planning shape): 13.5 V -> 6 V, 15 ms hold", "PWL(0 13.5 1m 13.5 6m 6 21m 6 41m 13.5)", 0.01, 60e-3, 50e-6),
    ("P5b", "Load dump, suppressed (pulse 5b / Test B): Us*=35 V, Ri=1 ohm, td=400 ms", loaddump(35, 0.4), 1, 1.2, 100e-6),
    ("LD_A", "INFORMATIONAL load dump Test A (unsuppressed): Us=101 V, Ri=2 ohm, td=400 ms", loaddump(101, 0.4), 2, 1.2, 100e-6),
    ("REV", "Reverse battery, 1 ms connection edge: 13.5 V -> -14 V, 50 mohm source", "PWL(0 13.5 10m 13.5 11m -14 120m -14)", 0.05, 120e-3, 10e-6),
    ("REVF", "Reverse battery, FAST 10 us edge (worst case): 13.5 V -> -14 V, 50 mohm source", "PWL(0 13.5 10m 13.5 10.01m -14 120m -14)", 0.05, 120e-3, 5e-6),
]


# Ri is only "in circuit" during the pulse window (ta..tb); before/after the supply path is 10 mohm.
WIN = {"P1": (T0, T0 + 6 * 2e-3 / math.log(2)), "P2a": (T0, T0 + 6 * 50e-6 / math.log(2)),
       "P3a": (T0, T0 + 6 * 150e-9 / math.log(2)), "P3b": (T0, T0 + 6 * 150e-9 / math.log(2)),
       "P5b": (50e-3, 1e3), "LD_A": (50e-3, 1e3)}


def netlist(desc, src, ri, tstop, step, name, rg):
    drive = f"V_SRC src 0 {src}" if src.startswith("PWL") else f"B_SRC src 0 V={src}"
    base = name.rsplit("_", 1)[0]
    ta, tb = WIN.get(base, (0, 1e3))
    rline = (f"R_RI  src bat R={{0.01+({ri}-0.01)*(u(time-{ta:.6g})-u(time-{tb:.6g}))}} ; generator Ri, active only during pulse"
             if base in WIN else f"R_RI  src bat {ri} ; source resistance")
    return f"""* {desc}
* SIMULATED in LTspice - generated by run_sims.py
{drive}
{rline}
* bidirectional TVS (two back-to-back diodes) at the connector
D_T1  bat mid TVS
D_T2  0   mid TVS
* reverse-battery P-FET: drain=bat, source=vin, gate pulled to GND, 15 V zener limits Vgs
M_Q1  bat gate vin vin PFET
R_G   gate 0 {rg}
D_Z   gate vin ZEN15
* bulk input capacitor and load (5 V/3 A converter at ~1.5 A input, modelled as a resistor)
C_IN  vin 0 10u
R_LD  vin 0 8
{TVS_MODEL}
{FET_MODEL}
.model ZEN15 D(Is=1n Bv=15 Ibv=1m Rs=5)
.tran 0 {tstop} 0 {step}
.save V(src) V(bat) V(mid) V(vin) V(gate) I(D_T1) I(D_T2) I(R_LD) I(R_RI)
.end
"""


def run(exe, name, desc, src, ri, tstop, step, rg):
    cir = os.path.join(NET, f"{name}.cir")
    with open(cir, "w") as f:
        f.write(netlist(desc, src, ri, tstop, step, name, rg))
    subprocess.run([exe, "-b", cir], capture_output=True, text=True, timeout=900)
    raw = os.path.join(NET, f"{name}.raw")
    if not os.path.exists(raw):
        sys.exit(f"{name}: no raw output.\n" + open(os.path.join(NET, name + ".log")).read())
    shutil.move(raw, os.path.join(RAW, f"{name}.raw"))
    shutil.move(os.path.join(NET, f"{name}.log"), os.path.join(RES, f"{name}.log"))
    for f in os.listdir(NET):
        if f.endswith(".op.raw"):
            os.remove(os.path.join(NET, f))
    return read_raw(os.path.join(RAW, f"{name}.raw"))


def metrics(d):
    t = d["time"]
    vb, vm, vi = d["V(bat)"], d["V(mid)"], d["V(vin)"]
    p = (vb - vm) * d["I(D_T1)"] + (0 - vm) * d["I(D_T2)"]   # total TVS dissipation
    i_tvs = np.maximum(np.abs(d["I(D_T1)"]), np.abs(d["I(D_T2)"]))
    vds, vgs = vb - vi, d["V(gate)"] - vi
    return dict(t=t, vb=vb, vi=vi, p=p, i=i_tvs, vds=vds, vgs=vgs,
                vbat_max=vb.max(), vbat_min=vb.min(), vin_max=vi.max(), vin_min=vi.min(),
                i_pk=i_tvs.max(), p_pk=p.max(), e=np.trapezoid(p, t),
                vds_max=np.abs(vds).max(), vgs_max=np.abs(vgs).max(), i_src_pk=np.abs(d["I(R_RI)"]).max())


def plot(name, desc, m):
    fig, ax = plt.subplots(4, 1, figsize=(9, 9), sharex=True)
    ms = m["t"][-1] > 5e-3
    tt, unit = m["t"] * (1e3 if ms else 1e6), ("ms" if ms else "us")
    ax[0].plot(tt, m["vb"], label="V(bat) connector node")
    ax[0].plot(tt, m["vi"], label="V(vin) after P-FET")
    ax[0].axhline(RATINGS["ic_vin"], ls=":", c="k")
    ax[0].axhline(-RATINGS["fet_vds"], ls=":", c="gray")
    ax[0].set_ylabel("V")
    ax[0].legend(fontsize=7)
    ax[1].plot(tt, m["i"])
    ax[1].axhline(RATINGS["tvs_ipp"], ls=":", c="k")
    ax[1].set_ylabel("TVS current (A)")
    ax[2].plot(tt, m["p"])
    ax[2].axhline(RATINGS["tvs_ppk"], ls=":", c="k")
    ax[2].set_ylabel("TVS power (W)")
    ax[3].plot(tt, m["vds"], label="Vds")
    ax[3].plot(tt, m["vgs"], label="Vgs")
    ax[3].legend(fontsize=7)
    ax[3].set_ylabel("P-FET (V)")
    ax[3].set_xlabel(f"time ({unit})")
    for a in ax:
        a.grid(alpha=.3)
    ax[0].set_title(f"LTspice simulation - {name}\n{desc}\n(dotted lines = component ratings)", fontsize=8)
    plt.tight_layout()
    plt.savefig(os.path.join(PLT, f"{name}.png"), dpi=120)
    plt.close()


def main():
    exe = find_ltspice()
    rows = []
    for (base, desc, src, ri, tstop, step), (rev, rg) in [(a, b) for b in REVS for a in SC]:
        name = f"{base}_{rev}"
        print("running", name, flush=True)
        m = metrics(run(exe, name, desc, src, ri, tstop, step, rg))
        plot(name, f"[design rev {rev}, R_G={rg}] " + desc, m)
        mult = 100 if base in ("P3a", "P3b") else 1   # 100 pulses per 10 ms burst (t1 = 100 us)
        e_tot = m["e"] * mult
        chk = {"TVS Ppk": m["p_pk"] <= RATINGS["tvs_ppk"], "TVS Ipp": m["i_pk"] <= RATINGS["tvs_ipp"],
               "TVS energy": e_tot <= RATINGS["tvs_e"], "Vin<=42": m["vin_max"] <= RATINGS["ic_vin"],
               "Vds<=60": m["vds_max"] <= RATINGS["fet_vds"], "Vgs<=20": m["vgs_max"] <= RATINGS["fet_vgs"],
               "Vin>=-0.3": m["vin_min"] >= -0.3}
        if base in ("REV", "REVF"):
            chk = {k: v for k, v in chk.items() if k in ("Vds<=60", "Vgs<=20", "Vin>=-0.3")}
        rows.append(dict(scenario=base, rev=rev, description=desc, vbat_max_V=m["vbat_max"], vbat_min_V=m["vbat_min"],
                         vin_max_V=m["vin_max"], vin_min_V=m["vin_min"], tvs_ipk_A=m["i_pk"], tvs_ppk_W=m["p_pk"],
                         tvs_energy_J=m["e"], energy_mult=mult, tvs_energy_total_J=e_tot,
                         fet_vds_max_V=m["vds_max"], fet_vgs_max_V=m["vgs_max"], src_current_pk_A=m["i_src_pk"],
                         verdict="PASS" if all(chk.values()) else "FAIL: " + ", ".join(k for k, v in chk.items() if not v)))
    with open(os.path.join(RES, "summary.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    R = RATINGS
    md = ["# Simulation results (generated by run_sims.py from LTspice runs)", "",
          f"TVS Ppk {R['tvs_ppk']:.0f} W, Ipp {R['tvs_ipp']} A, energy ref {R['tvs_e']} J; "
          f"Ratings: P-FET Vds {R['fet_vds']:.0f} V, Vgs ±{R['fet_vgs']:.0f} V; converter IC Vin abs-max {R['ic_vin']:.0f} V, abs-min -0.3 V. Rev A: R_G=10k, Rev B: R_G=1k. "
          "Ratings are assumptions from typical datasheet values - verify.", "",
          "| Scenario | Rev | V(bat) max / min (V) | V(vin) max / min (V) | TVS Ipk (A) | TVS Ppk (W) | TVS energy (J) | P-FET Vds / Vgs max (V) | Verdict |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        e = f"{r['tvs_energy_J']:.4g}" + (f" ×{r['energy_mult']} = {r['tvs_energy_total_J']:.4g} per burst" if r['energy_mult'] > 1 else "")
        md.append(f"| {r['scenario']} | {r['rev']} | {r['vbat_max_V']:.1f} / {r['vbat_min_V']:.1f} | {r['vin_max_V']:.1f} / {r['vin_min_V']:.1f} | "
                  f"{r['tvs_ipk_A']:.2f} | {r['tvs_ppk_W']:.1f} | {e} | {r['fet_vds_max_V']:.1f} / {r['fet_vgs_max_V']:.1f} | {r['verdict']} |")
    with open(os.path.join(RES, "summary.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
